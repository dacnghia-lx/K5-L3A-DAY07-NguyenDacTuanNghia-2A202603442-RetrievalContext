"""Read and normalize the corpus: CPython ``pydoc_data/topics.py`` snapshots.

Each snapshot file is a Python module containing one dict literal
``topics = {label: text}``. It is parsed with ``ast.literal_eval`` (never
executed). Every topic becomes one document per Python version; every section
(heading) inside a topic becomes one traceable "page".
"""
from __future__ import annotations

import ast
import hashlib
import re
import unicodedata
from pathlib import Path
from typing import Any

from .models import DocumentPage

# A heading is a non-empty line followed by an underline of one repeated
# punctuation character, at least as long as the title (Sphinx text writer).
_UNDERLINE = re.compile(r"^([*=\-~^\"'`#+])\1{2,}$")
_SNAPSHOT_RE = re.compile(r"Autogenerated by Sphinx on (.+)")


def normalize_text(text: str) -> str:
    """Normalize Unicode (NFC) and whitespace while keeping structure.

    - NFC keeps characters such as ``…`` or ``²`` intact (NFKC would rewrite them).
    - CRLF/CR -> LF, tabs -> 4 spaces, non-breaking/zero-width spaces handled.
    - Trailing spaces are removed; >2 consecutive blank lines collapse to 1 blank line.
    - Leading indentation is kept because it marks code and grammar blocks.
    """
    text = unicodedata.normalize("NFC", text)
    text = text.replace("\r\n", "\n").replace("\r", "\n").replace("\t", "    ")
    text = text.replace(" ", " ").replace("​", "").replace("﻿", "")
    lines = [line.rstrip() for line in text.split("\n")]
    text = "\n".join(lines)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


def flatten(text: str) -> str:
    """Whitespace-insensitive form used only for evidence matching."""
    return re.sub(r"\s+", " ", normalize_text(text)).strip()


def read_topics(path: Path) -> tuple[dict[str, str], str | None]:
    """Parse ``topics = {...}`` safely; return topics and the Sphinx snapshot date."""
    raw = path.read_text(encoding="utf-8")
    snapshot = None
    match = _SNAPSHOT_RE.search(raw[:500])
    if match:
        snapshot = match.group(1).strip()
    tree = ast.parse(raw, filename=str(path))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == "topics" for t in node.targets
        ):
            topics = ast.literal_eval(node.value)
            if not isinstance(topics, dict):
                raise ValueError(f"{path}: 'topics' is not a dict")
            return topics, snapshot
    raise ValueError(f"{path}: no 'topics = {{...}}' assignment found")


def split_sections(text: str) -> list[tuple[str, str]]:
    """Split normalized topic text into (heading, body) sections.

    Text before the first heading (rare) becomes a section with heading "".
    The heading line is kept as the first line of the section body so that the
    stored page text is exactly what a reader sees in the source.
    """
    lines = text.split("\n")
    starts: list[int] = []
    for i in range(len(lines) - 1):
        title, under = lines[i], lines[i + 1]
        if title.strip() and not title.startswith(" ") and _UNDERLINE.match(under) \
                and len(under) >= len(title.rstrip()) - 1:
            starts.append(i)
    if not starts or starts[0] != 0:
        starts = [0] + starts
    sections: list[tuple[str, str]] = []
    for idx, start in enumerate(starts):
        end = starts[idx + 1] if idx + 1 < len(starts) else len(lines)
        block = "\n".join(lines[start:end]).strip()
        heading = lines[start].strip() if start + 1 < len(lines) and _UNDERLINE.match(lines[start + 1]) else ""
        if block:
            sections.append((heading, block))
    return sections


def load_pydoc_topics(path: Path, python_version: str, source: str,
                      errors: list[dict[str, Any]] | None = None) -> list[DocumentPage]:
    """Load one snapshot into DocumentPage records (one per topic section).

    Empty topics/sections are not silently dropped: they are appended to
    ``errors`` so the run log shows what was skipped and why.
    """
    errors = errors if errors is not None else []
    topics, snapshot = read_topics(path)
    pages: list[DocumentPage] = []
    for topic in sorted(topics):
        raw = topics[topic]
        if not isinstance(raw, str):
            errors.append({"source": source, "topic": topic, "error": "non-string topic value"})
            continue
        text = normalize_text(raw)
        if not text:
            errors.append({"source": source, "topic": topic, "error": "empty topic after normalization"})
            continue
        document_id = f"py{python_version}/{topic}"
        topic_title = text.split("\n", 1)[0].strip()
        for number, (heading, body) in enumerate(split_sections(text), start=1):
            if len(body.strip()) == 0:
                errors.append({"source": source, "topic": topic, "page": number, "error": "empty section"})
                continue
            pages.append(DocumentPage(
                document_id=document_id,
                source=source,
                page=number,
                text=body,
                metadata={
                    "page_id": f"{document_id}#{number}",
                    "topic": topic,
                    "topic_title": topic_title,
                    "section": heading or topic_title,
                    "python_version": python_version,
                    "snapshot": snapshot or "",
                    "char_count": len(body),
                    "sha256": hashlib.sha256(body.encode("utf-8")).hexdigest()[:16],
                },
            ))
    return pages


